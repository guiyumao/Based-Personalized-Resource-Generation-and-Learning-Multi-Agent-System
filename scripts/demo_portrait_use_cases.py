"""Model-generated learning-portrait role use cases over real demo accounts.

Why this script exists
----------------------
The portrait page (智能支持 / 学习画像) no longer accepts hand-dragged sliders as
its primary source: the four Felder-Silverman axes are generated by the chat
model (``POST /users/{id}/learning-portrait/infer``) from evidence the platform
already collected — self-reported dimensions (``PUT .../learning-portrait``),
graded answers, resource interactions and profile conversations. Manual edits
still exist but only *override* individual axes; generation itself is the model.

This script exercises that feature with the real demo accounts and the real
model (DeepSeek, configured via .env). Nothing here fabricates axis values: the
script only supplies self-report text (a real product entry point) and triggers
inference; every returned axis value/confidence/evidence string is produced by
the model, persisted server-side, and read back through the public API.

What is asserted (structural facts, never exact model outputs):
  - before inference every axis is source=missing (0/4 on the radar);
  - after inference at least one axis is source=model_inferred with a value in
    [-1, 1], a confidence in [0, 1] and non-empty evidence text;
  - inference.status=completed, model name recorded, evidence counts > 0;
  - a second non-forced infer returns cached=True (fingerprint cache — no extra
    model spend);
  - a manual PUT on one axis flips that axis to source=user_reported and the
    model never overwrites it, while other axes stay model_inferred;
  - editing self-reported dimensions marks the stored inference stale=True;
  - another student gets 403 on read/infer of someone else's portrait, while
    demo_admin can read it;
  - demo_admin (no learning evidence) gets status=insufficient — the model is
    not asked to invent a portrait from nothing.

Usage:
    python scripts/demo_portrait_use_cases.py
    python scripts/demo_portrait_use_cases.py --students 8     # fewer model calls
    python scripts/demo_portrait_use_cases.py --verify-only    # assert stored state, no model calls

Outputs artifacts/demo-teaching/portrait-<ts>/result.json + report.md.
"""

