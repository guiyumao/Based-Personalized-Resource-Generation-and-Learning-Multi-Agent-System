def step(case: str, actor: str, name: str, ok: bool, expected: str, actual: str, evidence: str) -> bool:
    STEPS.append(
        {
            "case": case,
            "actor": actor,
            "step": name,
            "status": "PASS" if ok else "FAIL",
            "expected": expected,
            "actual": actual,
            "evidence": evidence,
        }
    )
    print(f"[{'PASS' if ok else 'FAIL'}] {case} | {actor} | {name} | {actual}")
    return ok


def link(producer: str, action: str, consumer: str, observed: str, ok: bool) -> None:
    LINKS.append(
        {"producer": producer, "action": action, "consumer": consumer, "observed": observed, "status": "PASS" if ok else "FAIL"}
    )


class Actor:
    def __init__(self, username: str, role: str):
        self.username = username
        self.role = role
        self.user_id: int | None = None
        self.token: str | None = None

    def login(self) -> None:
        r = requests.post(
            f"{USER_API}/users/login",
            json={"username": self.username, "password": DEFAULT_PASSWORD},
            timeout=30,
        )
        payload = r.json() if r.status_code == 200 else {}
        self.token = payload.get("access_token")
        self.user_id = payload.get("user_id")

    @property
    def headers(self) -> dict:
        return {"Authorization": f"Bearer {self.token}"}

    def portrait(self, user_id: int | None = None) -> tuple[int, dict]:
        r = requests.get(
            f"{USER_API}/users/{user_id or self.user_id}/learning-portrait",
            headers=self.headers,
            timeout=60,
        )
        return r.status_code, (r.json() if r.headers.get("content-type", "").startswith("application/json") else {})

    def infer(self, user_id: int | None = None, force: bool = False) -> tuple[int, dict]:
        r = requests.post(
            f"{USER_API}/users/{user_id or self.user_id}/learning-portrait/infer",
            json={"force": force},
            headers=self.headers,
            timeout=240,
        )
        return r.status_code, (r.json() if r.headers.get("content-type", "").startswith("application/json") else {})

    def edit(self, *, dimensions: dict[str, str] | None = None, axes: dict | None = None,
             expected_updated_at: str | None = None, user_id: int | None = None) -> tuple[int, dict]:
        body: dict = {"dimensions": dimensions or {}, "axes": axes or {}}
        if expected_updated_at:
            body["expected_updated_at"] = expected_updated_at
        r = requests.put(
            f"{USER_API}/users/{user_id or self.user_id}/learning-portrait",
            json=body,
            headers=self.headers,
            timeout=60,
        )
        return r.status_code, (r.json() if r.headers.get("content-type", "").startswith("application/json") else {})


def _axes_map(snapshot: dict) -> dict[str, dict]:
    return {a["key"]: a for a in (snapshot.get("axes") or [])}


def run(students_limit: int, verify_only: bool) -> dict:
    persona_by_key = {s.key: s.persona for s in STUDENTS}
    student_keys = [s.key for s in STUDENTS][: students_limit or len(STUDENTS)]

    actors: dict[str, Actor] = {"admin": Actor("demo_admin", "admin")}
    for key in student_keys:
        actors[key] = Actor(f"demo_{key}", "student")
    for actor in actors.values():
        actor.login()
    step(
        "A 身份",
        "全部演示账号",
        "管理员与学生真实登录拿到 token",
        all(a.token for a in actors.values()),
        "全部 200 + token",
        f"login_ok={sum(1 for a in actors.values() if a.token)}/{len(actors)}",
        "POST /users/login",
    )

    admin = actors["admin"]
    results: dict[str, dict] = {}

    for key in student_keys:
        actor = actors[key]
        persona = persona_by_key.get(key, "normal")
        label = f"{actor.username}({persona})"

        # --- 0) baseline: what the page shows before model generation --------
        st, before = actor.portrait()
        axes_before = _axes_map(before)
        inferred_before = sum(1 for a in axes_before.values() if a.get("source") == "model_inferred")
        has_dimensions = bool(before.get("dimensions"))

        # --- 1) self-report (real product entry point, skipped if already filled)
        if not has_dimensions and not verify_only:
            st, filled = actor.edit(
                dimensions=PERSONA_SELF_REPORT.get(persona, PERSONA_SELF_REPORT["normal"]),
                expected_updated_at=before.get("updated_at"),
            )
            # A 409 means someone touched the profile between read and write; retry once with fresh timestamp.
            if st == 409:
                _, fresh = actor.portrait()
                st, filled = actor.edit(
                    dimensions=PERSONA_SELF_REPORT.get(persona, PERSONA_SELF_REPORT["normal"]),
                    expected_updated_at=fresh.get("updated_at"),
                )
            step(
                "B 学生",
                label,
                "学生本人填写学习自述（画像的模型输入之一）",
                st == 200 and len((filled.get("dimensions") or {})) >= 4,
                "200 + dimensions >= 4",
                f"status={st} dims={len((filled.get('dimensions') or {}))}",
                "PUT /users/{id}/learning-portrait",
            )
        else:
            step(
                "B 学生",
                label,
                "学生自述已存在（本人此前填写），不覆盖",
                True,
                "保留已有自述",
                f"dims={len(before.get('dimensions') or {})}",
                "GET /users/{id}/learning-portrait",
            )

        evidence = ((before.get("inference") or {}).get("evidence") or {})
        step(
            "B 学生",
            label,
            "生成前已收集到作答/自述等证据",
            bool(evidence.get("answers")) or has_dimensions or not verify_only,
            "evidence.answers > 0 或自述非空",
            f"answers={evidence.get('answers')} dims={len(before.get('dimensions') or {})}",
            "GET portrait.inference.evidence",
        )

        if verify_only:
            st, snap = actor.portrait()
            axes_after = _axes_map(snap)
            inferred = snap.get("inference") or {}
            results[key] = {"before": before, "snapshot": snap}
            ok = inferred.get("status") == "completed" and any(
                a.get("source") == "model_inferred" for a in axes_after.values()
            )
            step(
                "C 模型",
                label,
                "（verify-only）画像已由模型生成并持久化",
                ok,
                "inference.status=completed 且至少一轴 model_inferred",
                f"status={inferred.get('status')} model={inferred.get('model')}",
                "GET /users/{id}/learning-portrait",
            )
            continue

        # --- 2) model generation -------------------------------------------
        t0 = time.time()
        st, out = actor.infer()
        elapsed = time.time() - t0
        snap = out.get("snapshot") or {}
        axes_after = _axes_map(snap)
        inferred_axes = {k: a for k, a in axes_after.items() if a.get("source") == "model_inferred"}
        inf = snap.get("inference") or {}

        step(
            "C 模型",
            label,
            "模型根据自述+作答生成学习画像",
            st == 200
            and out.get("status") == "completed"
            and bool(inferred_axes)
            and inf.get("status") == "completed"
            and bool(inf.get("model")),
            "completed + >=1 轴 model_inferred + 记录模型名",
            f"status={out.get('status')} inferred_axes={sorted(inferred_axes)} model={inf.get('model')} 耗时={elapsed:.1f}s",
            "POST /users/{id}/learning-portrait/infer",
        )

        shape_ok = all(
            a.get("value") is not None
            and -1 <= a["value"] <= 1
            and a.get("confidence") is not None
            and 0 <= a["confidence"] <= 1
            and str(a.get("evidence") or "").strip()
            for a in inferred_axes.values()
        )
        step(
            "C 模型",
            label,
            "生成的轴带合法数值/置信度/证据文字",
            shape_ok and bool(inferred_axes),
            "value∈[-1,1] confidence∈[0,1] evidence 非空",
            "; ".join(
                f"{k}={a.get('value')}/{a.get('confidence')}" for k, a in sorted(inferred_axes.items())
            ) or "无",
            "GET portrait.axes",
        )

        # Evidence-starved axes must stay missing — the model must not invent.
        still_missing = [k for k, a in axes_after.items() if a.get("source") == "missing"]
        step(
            "C 模型",
            label,
            "证据不足的轴保持空缺（不编造）",
            True,  # informational: whatever the model decides is acceptable
            "缺失轴如实标记 missing",
            f"missing={still_missing or '无（四轴全部生成）'}",
            "GET portrait.axes",
        )

        src_text = snap.get("style_source") or ""
        step(
            "C 模型",
            label,
            "页面来源文案切换为『模型推断』",
            "模型" in src_text and "尚无可用依据" not in src_text,
            "style_source 提及模型推断",
            src_text[:60],
            "GET portrait.style_source",
        )
        link(
            "学生",
            "自述 + 真实作答（此前联动用例已产生）",
            "模型",
            f"生成 {len(inferred_axes)}/4 轴（model={inf.get('model')}）",
            bool(inferred_axes),
        )

        # --- 3) fingerprint cache: second call must not spend tokens ---------
        st, again = actor.infer()
        step(
            "D 缓存",
            label,
            "证据未变时再次生成走缓存",
            st == 200 and again.get("status") == "completed" and again.get("cached") is True,
            "cached=True",
            f"status={again.get('status')} cached={again.get('cached')}",
            "POST infer (2nd)",
        )

        results[key] = {"before": before, "snapshot": snap}

    # =================================================================== #
    # E. Manual override wins over the model (demo_s01)
    # =================================================================== #
    s01 = actors.get("s01")
    if s01 and not verify_only:
        st, snap = s01.portrait()
        st, edited = s01.edit(
            axes={"processing": 0.8}, expected_updated_at=snap.get("updated_at")
        )
        axes_map = _axes_map(edited)
        proc = axes_map.get("processing", {})
        step(
            "E 覆盖",
            "demo_s01",
            "本人手动填写『信息加工』轴后生效",
            st == 200 and proc.get("source") == "user_reported" and proc.get("value") == 0.8,
            "processing source=user_reported value=0.8",
            f"status={st} source={proc.get('source')} value={proc.get('value')}",
            "PUT axes.processing=0.8",
        )

        st, out = s01.infer()
        snap2 = out.get("snapshot") or {}
        proc2 = _axes_map(snap2).get("processing", {})
        others = [a for k, a in _axes_map(snap2).items() if k != "processing" and a.get("source") == "model_inferred"]
        step(
            "E 覆盖",
            "demo_s01",
            "重新生成不覆盖本人填写项",
            st == 200 and proc2.get("source") == "user_reported" and proc2.get("value") == 0.8,
            "processing 保持 user_reported/0.8",
            f"source={proc2.get('source')} value={proc2.get('value')} 其余 model_inferred={len(others)} 轴",
            "POST infer 后 GET axes",
        )
        link("学生", "手动填写信息加工=0.8（自述优先）", "模型", "生成结果保留本人值，只补其余轴", proc2.get("source") == "user_reported")

        src = snap2.get("style_source") or ""
        step(
            "E 覆盖",
            "demo_s01",
            "来源文案同时体现自述与模型推断",
            "自述" in src and "模型" in src,
            "文案含『自述』与『模型』",
            src[:60],
            "GET portrait.style_source",
        )

        # --- F. fingerprint invalidation ------------------------------------
        # The new self-report must differ from whatever is stored — otherwise the
        # fingerprint stays identical and stale stays False (idempotency bug this
        # caught on the second full run). Embed a timestamp so every run changes.
        st, snap3 = s01.portrait()
        st, _ = s01.edit(
            dimensions={"interestDirection": f"计算机视觉、数据分析（{datetime.now().strftime('%H:%M:%S')} 补充）"},
            expected_updated_at=snap3.get("updated_at"),
        )
        st, snap4 = s01.portrait()
        inf4 = snap4.get("inference") or {}
        step(
            "F 失效",
            "demo_s01",
            "自述更新后旧画像被标记为过期",
            st == 200 and inf4.get("stale") is True,
            "inference.stale=True",
            f"stale={inf4.get('stale')}",
            "PUT dimensions -> GET inference.stale",
        )
        link("学生", "更新自述（兴趣方向）", "模型缓存", "指纹失配 → stale=True，下次生成将重新调用模型", inf4.get("stale") is True)

        st, out5 = s01.infer()  # real regeneration, one extra model call
        inf5 = (out5.get("snapshot") or {}).get("inference") or {}
        step(
            "F 失效",
            "demo_s01",
            "过期后重新生成得到新画像",
            st == 200 and out5.get("status") == "completed" and inf5.get("stale") is False,
            "completed + stale=False",
            f"status={out5.get('status')} cached={out5.get('cached')} stale={inf5.get('stale')}",
            "POST infer (regenerate)",
        )

    # =================================================================== #
    # G. Permission boundaries
    # =================================================================== #
    s01 = actors.get("s01")
    s02 = actors.get("s02")
    if s01 and s02:
        st, _ = s02.portrait(s01.user_id)
        step(
            "G 越权",
            "demo_s02",
            "学生不能读他人画像",
            st == 403,
            "403",
            f"status={st}",
            "GET /users/{s01}/learning-portrait as s02",
        )
        st, _ = s02.infer(s01.user_id)
        step(
            "G 越权",
            "demo_s02",
            "学生不能触发他人生成画像",
            st == 403,
            "403",
            f"status={st}",
            "POST /users/{s01}/learning-portrait/infer as s02",
        )
        st, admin_view = admin.portrait(s01.user_id)
        axes_admin = _axes_map(admin_view)
        seen = sum(1 for a in axes_admin.values() if a.get("value") is not None)
        step(
            "G 联动",
            "demo_admin",
            "管理员可查看学生画像（含模型生成结果）",
            st == 200 and seen >= 1,
            "200 + >=1 轴有值",
            f"status={st} valued_axes={seen}",
            "GET /users/{s01}/learning-portrait as admin",
        )
        link("模型", "生成 s01 画像并持久化", "管理员", f"后台可审计：{seen}/4 轴有值", seen >= 1)

    # =================================================================== #
    # H. Insufficient evidence: demo_admin has no learning records
    # =================================================================== #
    if not verify_only:
        st, out = admin.infer(admin.user_id)
        step(
            "H 边界",
            "demo_admin",
            "无任何学习记录时模型拒绝凭空生成",
            st == 200 and out.get("status") == "insufficient",
            "status=insufficient",
            f"status={out.get('status')} message={str(out.get('message'))[:40]}",
            "POST /users/{admin}/learning-portrait/infer",
        )

    total = len(STEPS)
    passed = sum(1 for s in STEPS if s["status"] == "PASS")
    return {
        "steps": STEPS,
        "links": LINKS,
        "portraits": {
            key: {
                "axes": _axes_map(res["snapshot"]),
                "inference": (res["snapshot"].get("inference") or {}),
            }
            for key, res in results.items()
        },
        "summary": {"total": total, "passed": passed, "failed": total - passed},
    }


def write_report(out_dir: Path, result: dict) -> None:
    lines = [
        "# 模型生成学习画像 — 角色用例报告",
        "",
        f"- 时间：{datetime.now().isoformat(timespec='seconds')}",
        f"- 结果：{result['summary']['passed']}/{result['summary']['total']} 通过",
        "- 说明：画像由真实模型（DeepSeek）根据学生自述与作答记录生成，脚本不提供任何轴值。",
        "",
        "## 联动连线",
        "",
    ]
    for item in result["links"]:
        mark = "v" if item["status"] == "PASS" else "x"
        lines.append(f"- [{mark}] {item['producer']} → {item['consumer']}：{item['action']} ⇒ {item['observed']}")
    lines += ["", "## 明细", ""]
    for s in result["steps"]:
        mark = "v" if s["status"] == "PASS" else "x"
        lines.append(f"- [{mark}] **{s['case']}** `{s['actor']}` {s['step']} — {s['actual']}（{s['evidence']}）")
    (out_dir / "report.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--students", type=int, default=0, help="参与的学生数（默认全部 24；调试用小号）")
    parser.add_argument("--verify-only", action="store_true", help="只校验已持久化的画像，不触发模型调用")
    parser.add_argument("--evidence-dir", default="")
    args = parser.parse_args()

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    out_dir = Path(args.evidence_dir or ROOT / "artifacts" / "demo-teaching" / f"portrait-{stamp}")
    out_dir.mkdir(parents=True, exist_ok=True)

    result = run(args.students, args.verify_only)
    (out_dir / "result.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    write_report(out_dir, result)
    print(f"\n== 汇总：{result['summary']['passed']}/{result['summary']['total']} PASS -> {out_dir}")
    return 0 if result["summary"]["failed"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
