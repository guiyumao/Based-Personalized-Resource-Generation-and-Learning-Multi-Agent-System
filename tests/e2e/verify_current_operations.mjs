// Explicit current-runtime acceptance; credentials arrive only through stdin.
import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
import {loadPlaywright} from './lib/env.mjs'
const input=JSON.parse(fs.readFileSync(0,'utf8'))
const dir=input.output; fs.mkdirSync(dir,{recursive:true})
const {module:pw}=loadPlaywright()
const browser=await pw.chromium.launch({headless:true})
const context=await browser.newContext({viewport:{width:1500,height:1050}})
await context.route('**/*',route=>['127.0.0.1','localhost'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort())
const page=await context.newPage();page.setDefaultTimeout(120000)
const report={passed:false,currentRuntime:true,paidCalls:0,checks:[],pageErrors:[]}
page.on('pageerror',error=>report.pageErrors.push(String(error)))
const headers=auth=>({Authorization:'Bearer '+auth.token})
async function asUser(auth,url) {
 await page.goto('http://127.0.0.1:5175/')
 await page.evaluate(value=>localStorage.setItem('learning-system-auth',JSON.stringify(value)),auth)
 await page.goto('http://127.0.0.1:5175'+url)
}
try {
 const before=await context.request.get('http://127.0.0.1:8002/admin/usage',{headers:headers(input.admin)})
 assert.equal(before.status(),200);const calls=(await before.json()).summary.calls
 await asUser(input.admin,'/admin/tasks')
 const panel=page.getByRole('region',{name:'模型调用台账与Worker心跳'})
 await panel.getByText(new RegExp(`已记录 ${calls} 次调用`)).waitFor()
 await panel.getByRole('cell',{name:'ONLINE',exact:true}).first().waitFor()
 await panel.locator('summary').filter({hasText:'设置模型调用预算'}).click()
 await panel.getByRole('button',{name:'保存调用预算',exact:true}).click()
 await panel.getByText('调用预算已保存并生效。',{exact:true}).waitFor()
 await page.screenshot({path:path.join(dir,'admin-live.png'),fullPage:true})
 report.checks.push('current_admin_usage_budget_save_and_online_worker')
 const binding=await context.request.post('http://127.0.0.1:8002/learning/contexts',{headers:headers(input.student),data:input.binding})
 assert.ok([200,201].includes(binding.status()),'Context creation HTTP '+binding.status())
 const ctx=(await binding.json()).id; report.contextId=ctx
 await asUser(input.student,'/student/workspace/'+ctx)
 const artifacts=page.getByRole('region',{name:'本地学习产物'})
 await artifacts.waitFor()
 await artifacts.getByRole('button',{name:'生成PPTX',exact:true}).click()
 await artifacts.getByRole('button',{name:'下载PPTX',exact:true}).waitFor()
 const downloadWait=page.waitForEvent('download')
 await artifacts.getByRole('button',{name:'下载PPTX',exact:true}).click()
 await (await downloadWait).saveAs(path.join(dir,'current-resource.pptx'))
 assert.equal(fs.readFileSync(path.join(dir,'current-resource.pptx')).subarray(0,2).toString(),'PK')
 await artifacts.getByRole('button',{name:'生成步骤动画',exact:true}).click()
 const animation=artifacts.locator('article').filter({hasText:'animation'})
 await animation.getByRole('button',{name:'加载预览'}).click()
 await page.waitForFunction(()=>document.querySelector('.resource-artifacts img')?.naturalWidth>0)
 const frame=await animation.getByRole('img').screenshot()
 await page.waitForTimeout(1500)
 assert.ok(!frame.equals(await animation.getByRole('img').screenshot()))
 await artifacts.getByRole('button',{name:'生成语音',exact:true}).click()
 const audio=artifacts.locator('article').filter({hasText:'audio'})
 await audio.getByRole('button',{name:'加载预览'}).click()
 await page.waitForFunction(()=>document.querySelector('.resource-artifacts audio')?.readyState>=1)
 assert.ok(await audio.locator('audio').evaluate(el=>el.duration>0))
 await audio.locator('audio').evaluate(async el=>{el.muted=true;await el.play()})
 await page.waitForTimeout(500)
 assert.ok(await audio.locator('audio').evaluate(el=>el.currentTime>0))
 await audio.locator('audio').evaluate(el=>el.pause())
 await page.screenshot({path:path.join(dir,'student-live.png'),fullPage:true})
 report.checks.push('current_worker_pptx_download_animation_and_wav_playback')
 await asUser(input.student,'/student/resources?resource='+input.demoMapId)
 const map=page.getByRole('region',{name:'思维导图编辑器'})
 await map.getByRole('textbox',{name:'节点child名称',exact:true}).fill('子节点（已保存）')
 await map.getByRole('button',{name:'放大',exact:true}).click()
 const saved=page.waitForResponse(response=>response.url().endsWith(`/learning/resources/${input.demoMapId}/mindmap`)&&response.request().method()==='PUT')
 await map.getByRole('button',{name:'保存导图新版本',exact:true}).click()
 assert.equal((await saved).status(),200)
 await map.getByRole('button',{name:'读取版本历史',exact:true}).click()
 await map.getByText('已保存版本',{exact:true}).waitFor()
 const reread=await context.request.get(`http://127.0.0.1:8002/learning/resources/${input.demoMapId}/mindmap`,{headers:headers(input.student)})
 assert.ok((await reread.json()).structured_json.includes('子节点（已保存）'))
 await page.screenshot({path:path.join(dir,'mindmap-live.png'),fullPage:true})
 report.checks.push('current_resource_center_mindmap_edit_save_history_readback_on_labeled_local_demo')
 await asUser(input.admin,'/admin/tasks')
 await page.getByRole('region',{name:'持久任务运营概览'}).getByRole('button',{name:'查看',exact:true}).first().click()
 const dialog=page.getByRole('dialog',{name:'任务执行记录'})
 await dialog.getByRole('heading',{name:'执行尝试',exact:true}).waitFor()
 await dialog.getByRole('cell',{name:'SUCCEEDED',exact:true}).waitFor()
 await page.screenshot({path:path.join(dir,'attempt-live.png'),fullPage:true})
 const after=await context.request.get('http://127.0.0.1:8002/admin/usage',{headers:headers(input.admin)})
 assert.equal((await after.json()).summary.calls,calls)
 report.checks.push('current_attempt_history_and_unchanged_provider_call_count')
 assert.deepEqual(report.pageErrors,[])
 report.passed=true
} catch(error) {
 report.error=String(error.stack??error)
 await page.screenshot({path:path.join(dir,'failure.png'),fullPage:true}).catch(()=>{})
 process.exitCode=1
} finally {
 fs.writeFileSync(path.join(dir,'result.json'),JSON.stringify(report,null,2))
 await browser.close()
}
