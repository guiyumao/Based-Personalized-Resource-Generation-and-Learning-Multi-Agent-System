import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
import { loadPlaywright } from './lib/env.mjs'
const { module: pw } = loadPlaywright()
const origin = process.env.E2E_BASE_URL, api = process.env.WORKSPACE_API, dir = process.env.WORKSPACE_ARTIFACTS
assert.ok(dir && api && process.env.NO_COST_TEST === '1')
const browser = await pw.chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1600, height: 1100 } })
await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
const page = await context.newPage()
page.setDefaultTimeout(20000)
const report = { passed: false, isolated: true, generation: 'controlled workflow and model stubs', realModelCalls: 0, steps: [], pageErrors: [] }
page.on('pageerror', error => report.pageErrors.push(String(error)))
const login = async username => {
  const response = await context.request.post(`${api}/user/users/login`, { data: { username, password: process.env.WORKSPACE_PASSWORD } })
  assert.equal(response.status(), 200)
  return response.json()
}
try {
  const auth = await login('workspace-student')
  const headers = { Authorization: `Bearer ${auth.access_token}` }
  await page.goto(origin + '/login')
  await page.evaluate(auth => localStorage.setItem('learning-system-auth', JSON.stringify({ token: auth.access_token, user: { userId: auth.user_id, username: auth.username, role: auth.role } })), auth)
  await page.goto(origin + '/student/workspace')
  await page.getByRole('button', { name: '阅读TCP课件2 TCP' }).click()
  await page.waitForURL('**/student/workspace/*')
  const taskContext = page.url().split('/').at(-1)
  await page.getByRole('button', { name: 'TCP版本课件', exact: true }).click()
  await page.getByRole('heading', { name: 'TCP可靠传输' }).waitFor()
  const sourceContext = page.url().split('/').at(-1)
  assert.notEqual(sourceContext, taskContext)
  assert.equal(await page.getByText('其他账户私人课件').count(), 0)
  await page.reload()
  await page.getByRole('heading', { name: 'TCP可靠传输' }).waitFor()
  report.steps.push('persisted_plan_task_resource_version_context_survives_refresh_and_hides_other_owner')
  await page.getByRole('textbox', { name: '围绕当前资源提问' }).fill('解释当前课件')
  await page.getByRole('button', { name: '提问', exact: true }).click()
  await page.getByText('隔离模型桩：当前TCP课件使用序列号与确认机制。', { exact: true }).waitFor()
  report.steps.push('real_assistant_route_passes_server_source_excerpt_to_controlled_model')
  await page.getByRole('textbox', { name: '笔记标题', exact: true }).fill('TCP上下文笔记')
  await page.getByRole('textbox', { name: '笔记正文', exact: true }).fill('序列号和确认支持可靠传输。')
  await page.getByRole('button', { name: '保存笔记', exact: true }).click()
  await page.getByRole('status').filter({ hasText: '笔记已保存' }).waitFor()
  const notes = await context.request.get(`${api}/user/study/notes`, { headers })
  const note = (await notes.json()).items.find(row => row.title === 'TCP上下文笔记')
  assert.equal(note.learning_context_id, sourceContext)
  assert.equal(note.source_resource_version.length, 64)
  report.steps.push('note_persists_context_and_resource_version_in_real_sqlite')
  await page.getByRole('button', { name: '生成3道练习', exact: true }).click()
  await page.getByRole('heading', { name: 'TCP隔离练习1：可靠传输依赖什么？' }).waitFor()
  const quizzes = page.locator('.workspace-quiz')
  assert.equal(await quizzes.count(), 3)
  await quizzes.first().getByRole('textbox').fill('A')
  await quizzes.first().getByRole('button', { name: '提交作答' }).click()
  await quizzes.first().getByText('回答正确', { exact: false }).waitFor()
  await page.reload()
  await page.locator('.workspace-quiz').first().getByText('回答正确', { exact: false }).waitFor()
  const snapshot = await context.request.get(`${api}/agent/learning/contexts/${sourceContext}`, { headers })
  assert.equal((await snapshot.json()).task.learning_evidence.graded_exercises, 1)
  report.steps.push('real_durable_task_lease_exercise_persistence_binding_grade_and_plan_evidence_readback')
  if (process.env.LOCAL_ARTIFACT_TEST === '1') {
    const panel = page.getByRole('region', { name:'本地学习产物' })
    await panel.getByRole('button',{name:'生成PPTX',exact:true}).click()
    await panel.getByRole('button',{name:'下载PPTX',exact:true}).waitFor()
    const downloadPromise = page.waitForEvent('download')
    await panel.getByRole('button',{name:'下载PPTX',exact:true}).click()
    const download = await downloadPromise
    await download.saveAs(path.join(dir,'browser-export.pptx'))
    assert.equal(fs.readFileSync(path.join(dir,'browser-export.pptx')).subarray(0,2).toString(),'PK')
    await panel.getByRole('button',{name:'生成步骤动画',exact:true}).click()
    const animation = panel.locator('article').filter({hasText:'animation'})
    await animation.getByRole('button',{name:'加载预览'}).click()
    const image=animation.getByRole('img')
    await page.waitForFunction(()=>document.querySelector('.resource-artifacts img')?.naturalWidth>0)
    const frame1=await image.screenshot()
    await page.waitForTimeout(1500)
    const frame2=await image.screenshot()
    assert.ok(!frame1.equals(frame2),'SVG animation frames must change')
    await panel.getByRole('button',{name:'生成语音',exact:true}).click()
    const audio = panel.locator('article').filter({hasText:'audio'})
    await audio.getByRole('button',{name:'加载预览'}).click()
    await page.waitForFunction(()=>document.querySelector('.resource-artifacts audio')?.readyState>=1)
    assert.ok(await audio.locator('audio').evaluate(el=>el.duration>0))
    await audio.locator('audio').evaluate(async el=>{el.muted=true;await el.play()})
    await page.waitForTimeout(500)
    assert.ok(await audio.locator('audio').evaluate(el=>el.currentTime>0))
    await audio.locator('audio').evaluate(el=>el.pause())
    report.steps.push('real_worker_pptx_download_svg_animation_frames_and_local_wav_playback')
    await page.getByRole('button',{name:'TCP导图',exact:true}).click()
    await page.getByRole('region',{name:'思维导图编辑器'}).waitFor()
    const mapContext=page.url().split('/').at(-1)
    await page.getByRole('textbox',{name:'节点n1名称',exact:true}).fill('确认与超时重传')
    await page.getByRole('button',{name:'保存导图新版本',exact:true}).click()
    await page.getByText('导图新版本已保存，请重新选择任务和资源。',{exact:true}).waitFor()
    assert.equal((await context.request.get(`${api}/agent/learning/contexts/${mapContext}`,{headers})).status(),409)
    const history=await context.request.get(`${api}/agent/learning/contexts/${mapContext}/resource-history`,{headers})
    assert.equal((await history.json()).items.length,2)
    await page.getByRole('button',{name:'阅读TCP课件2 TCP'}).click()
    await page.getByRole('button',{name:'TCP导图',exact:true}).click()
    await page.getByRole('textbox',{name:'节点n1名称',exact:true}).waitFor()
    assert.equal(await page.getByRole('textbox',{name:'节点n1名称',exact:true}).inputValue(),'确认与超时重传')
    report.steps.push('mindmap_edit_immutable_history_stale_binding_rejected_and_new_version_readback')
    await page.goto(origin+`/student/workspace/${sourceContext}`)
    await page.locator('.workspace-quiz').first().getByText('回答正确',{exact:false}).waitFor()
  }
  for (const width of [1600, 1024, 390]) {
    await page.setViewportSize({ width, height: 1100 })
    if (width === 390) {
      if (await page.locator('.app-sidebar.mobile-open').count()) await page.locator('.mobile-close').click()
      await page.getByRole('button', { name: '学习目录', exact: true }).click()
      assert.equal(await page.locator('.workspace-outline').count(), 0)
      await page.getByRole('button', { name: '学习工具', exact: true }).click()
      assert.equal(await page.locator('.workspace-tools').count(), 0)
    }
    await page.waitForTimeout(350)
    assert.ok(await page.locator('.study-workspace').evaluate(el => el.scrollWidth <= el.clientWidth + 1))
    await page.screenshot({ path: path.join(dir, `workspace-${width}.png`), fullPage: true })
    if (width === 390) {
      await page.getByRole('button', { name: '学习目录', exact: true }).click()
      await page.getByRole('button', { name: '学习工具', exact: true }).click()
    }
  }
  report.steps.push('desktop_tablet_mobile_widths_no_workspace_overflow')
  const other = await login('workspace-other')
  const denied = await context.request.get(`${api}/agent/learning/contexts/${sourceContext}`, { headers: { Authorization: `Bearer ${other.access_token}` } })
  assert.equal(denied.status(), 404)
  const tampered = await context.request.post(`${api}/agent/learning/contexts`, { headers, data: { client_request_id: 'browser-stale-version', plan_id: 2, module_id: 's1', task_key: 't1', resource_id: 1, expected_resource_version: '0'.repeat(64) } })
  assert.equal(tampered.status(), 409)
  const oldTab = await context.newPage()
  await oldTab.goto(origin + `/student/workspace/${sourceContext}`)
  await oldTab.getByRole('heading', { name: 'TCP可靠传输' }).waitFor()
  await page.setViewportSize({ width: 1600, height: 1100 })
  await page.locator('.workspace-outline .el-select__wrapper').click()
  await page.getByRole('option', { name: '计算机网络 · TCP 计划1' }).click()
  await page.waitForURL(url => url.pathname === '/student/workspace' && url.searchParams.has('plan'))
  await page.getByRole('button', { name: '阅读TCP课件1 TCP' }).click()
  await page.waitForURL('**/student/workspace/*')
  assert.notEqual(page.url().split('/').at(-1), sourceContext)
  assert.equal(await page.locator('.workspace-answer').count(), 0)
  await oldTab.reload()
  await oldTab.getByRole('heading', { name: 'TCP可靠传输' }).waitFor()
  report.steps.push('cross_account_404_stale_version_409_plan_switch_clears_qa_and_other_tab_keeps_immutable_context')
  const admin = await login('workspace-admin')
  await page.evaluate(auth => localStorage.setItem('learning-system-auth', JSON.stringify({ token: auth.access_token, user: { userId: auth.user_id, username: auth.username, role: auth.role } })), admin)
  await page.goto(origin + '/admin')
  const operations = page.getByRole('region', { name: '持久任务运营概览' })
  await operations.getByText(`SUCCEEDED ${process.env.LOCAL_ARTIFACT_TEST === '1' ? 4 : 1}`, { exact: true }).waitFor()
  await operations.getByRole('heading', { name: '模型调用台账与 Worker 心跳', exact: true }).waitFor()
  if (process.env.OPERATIONS_LEDGER_TEST === '1') {
    await page.locator('.usage-worker .el-select__wrapper').first().click()
    await page.getByRole('option', { name: '隔离测试调用', exact: true }).click()
    await operations.getByText(/已记录 3 次调用/).waitFor()
    await operations.getByText(/ONLINE/).waitFor()
    await operations.getByText(/输入 Token：UNKNOWN/).waitFor()
  }
  await operations.getByRole('button', { name: '查看', exact: true }).first().click()
  await page.getByRole('dialog', { name: '任务执行记录' }).waitFor()
  await page.getByRole('dialog', { name: '任务执行记录' }).getByText(/用户 #/).waitFor()
  await page.waitForTimeout(350)
  await page.screenshot({ path: path.join(dir, 'admin-task-operations.png'), fullPage: true })
  report.steps.push('admin_real_completed_task_count_detail_and_unknown_usage_are_visible')
  assert.deepEqual(report.pageErrors, [])
  report.passed = true
} catch (error) {
  report.error = String(error.stack ?? error)
  await page.screenshot({ path: path.join(dir, 'workspace-failure.png'), fullPage: true }).catch(() => {})
  throw error
} finally {
  fs.writeFileSync(path.join(dir, 'browser-report.json'), JSON.stringify(report, null, 2))
  await browser.close()
}
