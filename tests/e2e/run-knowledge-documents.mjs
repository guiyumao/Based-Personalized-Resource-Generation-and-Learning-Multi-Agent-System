import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'
import { loadPlaywright } from './lib/env.mjs'
const { module: pw } = loadPlaywright()
const root = process.env.DOCS_ARTIFACTS, api = process.env.DOCS_API, origin = process.env.E2E_BASE_URL
assert.ok(root && api && process.env.NO_COST_TEST === '1')
const browser = await pw.chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
await context.route('**/*', route => [api, origin].includes(new URL(route.request().url()).origin) ? route.continue() : route.abort())
const page = await context.newPage()
page.setDefaultTimeout(20000)
const report = { passed: false, mocked: false, realChroma: true, paidCalls: 0, steps: [], pageErrors: [], apiErrors: [] }
report.requestFailures=[]
page.on('requestfailed', req=>report.requestFailures.push({url:req.url(),error:req.failure()?.errorText}))
page.on('pageerror', e => report.pageErrors.push(String(e)))
page.on('response', r => { if (r.url().startsWith(api) && r.status() >= 400) report.apiErrors.push({ url:r.url().replace(api,''), status:r.status() }) })
const shot = name => page.screenshot({ path: path.join(root, name + '.png'), fullPage: true })
try {
  await page.goto(origin + '/login')
  await page.locator('input[autocomplete=username]').fill('documents-admin')
  await page.locator('input[autocomplete=current-password]').fill(process.env.DOCS_PASSWORD)
  await page.getByRole('button',{ name:'登录', exact:true }).click()
  await page.waitForURL('**/admin')
  await page.goto(origin + '/admin/knowledge')
  await page.getByRole('heading', { name:'查看正文与资料分类' }).waitFor()
  const upload = page.waitForResponse(r => r.url().endsWith('/documents/upload') && r.request().method() === 'POST')
  await page.locator('input[type=file]').setInputFiles(path.join(root,'sample.pdf'))
  const uploaded = await (await upload).json()
  const id = uploaded.id
  await page.locator('.document-detail').getByText('AURA_DOC_VECTOR_MARKER', { exact:false }).waitFor()
  report.steps.push('pdf_upload_and_real_text_extraction')
  const box = page.locator('.classification-box')
  await box.locator('.el-select').nth(0).click()
  await page.getByRole('option', { name:'隔离文档数学', exact:true }).click()
  await box.locator('.el-select').nth(1).click()
  await page.getByRole('option', { name:'向量谱线', exact:true }).click()
  await page.keyboard.press('Escape')
  const save = page.waitForResponse(r => r.url().endsWith('/documents/classify') && r.request().method() === 'POST')
  await page.getByRole('button',{ name:'保存当前文档分类', exact:true }).click()
  assert.equal((await save).status(),200)
  await page.reload()
  await page.getByRole('button',{ name:'sample', exact:true }).click()
  await page.locator('.document-detail').getByText('AURA_DOC_VECTOR_MARKER', { exact:false }).waitFor()
  await shot('document-parsed-and-classified')
  const auth = await page.evaluate(() => JSON.parse(localStorage.getItem('learning-system-auth')))
  const headers = { Authorization:`Bearer ${auth.token}` }
  const detail = await (await context.request.get(`${api}/agent/knowledge-base/admin/documents/${id}`,{ headers })).json()
  assert.equal(detail.point_ids.length,1)
  assert.ok(detail.subject_id)
  assert.equal(detail.status,'DRAFT')
  const studentLogin = await (await context.request.post(`${api}/user/users/login`,{ data:{username:'documents-student',password:process.env.DOCS_PASSWORD} })).json()
  const student = { Authorization:`Bearer ${studentLogin.access_token}` }
  const before = await context.request.get(`${api}/agent/knowledge-base/search`,{ headers:student, params:{q:'AURA_DOC_VECTOR_MARKER',subject:'document_math',retrieval_mode:'lexical'} })
  assert.equal(before.status(),200)
  assert.deepEqual((await before.json()).items,[])
  const staged = page.waitForResponse(r => r.url().endsWith(`/documents/${id}/candidate`))
  await page.getByRole('button',{ name:'创建审核草稿',exact:true }).click()
  const candidate = await (await staged).json()
  await page.getByRole('link',{ name:/前往审核与发布/ }).click()
  const card = page.locator(`[data-candidate-id="${candidate.id}"]`)
  await card.getByPlaceholder('许可证标识').fill('INTERNAL_TEST_ONLY')
  await card.getByPlaceholder('许可依据 URL').fill('https://example.org/license')
  await card.getByText('已核验全文发布许可',{exact:true}).click()
  await card.getByRole('button',{name:'提交审核',exact:true}).click()
  await card.getByRole('button',{name:'批准',exact:true}).click()
  await card.getByRole('button',{name:'发布并验证检索',exact:true}).click()
  const [queued] = await Promise.all([
    page.waitForResponse(r => r.url().endsWith('/publish-task')),
    page.locator('.el-message-box__btns .el-button--primary').click(),
  ])
  assert.equal(queued.status(),202)
  const task = await queued.json()
  let completed
  for(let i=0;i<120;i++) {
    const result = await (await context.request.get(`${api}/agent/knowledge-base/tasks/${task.id}`,{headers})).json()
    if(result.status === 'COMPLETED') { completed=result; break }
    assert.ok(!['FAILED','CANCELLED'].includes(result.status),JSON.stringify(result))
    await page.waitForTimeout(500)
  }
  assert.ok(completed,'Worker did not complete publication')
  await page.getByRole('button',{name:'刷新',exact:true}).first().click()
  await card.getByRole('button',{name:'创建修订草稿',exact:true}).waitFor()
  await shot('review-published')
  const search = await context.request.get(`${api}/agent/knowledge-base/search`,{headers:student,params:{q:'AURA_DOC_VECTOR_MARKER',subject:'document_math',retrieval_mode:'lexical'}})
  assert.equal(search.status(),200)
  assert.ok(JSON.stringify((await search.json()).items).includes('AURA_DOC_VECTOR_MARKER'))
  report.steps.push('draft_hidden_then_review_worker_real_chroma_student_hit')
  const original = await context.request.get(`${api}/agent/knowledge-base/admin/documents/${id}/original`,{headers})
  assert.equal(Buffer.compare(await original.body(),fs.readFileSync(path.join(root,'sample.pdf'))),0)
  assert.equal((await context.request.get(`${api}/agent/knowledge-base/admin/documents/${id}/original`,{headers:student})).status(),403)
  assert.equal((await context.request.get(`${api}/agent/knowledge-base/admin/documents/${id}/original`)).status(),401)
  const list = await (await context.request.get(`${api}/agent/knowledge-base/admin/documents`,{headers})).json()
  assert.equal(list.total,1,'published corpus must not duplicate the upload catalog row')
  const chunks = await (await context.request.get(`${api}/agent/knowledge-base/admin/documents/${id}/chunks`,{headers})).json()
  assert.ok(chunks.items.some(c=>c.text.includes('AURA_DOC_VECTOR_MARKER')))
  const coverage = await (await context.request.get(`${api}/agent/knowledge-base/admin/subjects/${detail.subject_id}/coverage`,{headers})).json()
  assert.equal(coverage.covered_points,1)
  report.steps.push('original_bytes_admin_only_catalog_deduplicated_chunks_and_coverage')
  await page.goto(origin+'/admin/knowledge')
  await page.getByRole('button',{name:'sample',exact:true}).click()
  await page.getByRole('tab',{name:'实时向量片段',exact:true}).click()
  await page.getByRole('button',{name:'加载实时 Chunk',exact:true}).click()
  await page.locator('.document-detail h4').first().waitFor()
  await shot('document-live-chunks')
  await page.getByRole('tab',{name:'版本与审核记录',exact:true}).click()
  await page.getByRole('button',{name:'读取版本与审核记录',exact:true}).click()
  await page.locator('.document-detail').getByText(/knowledge\.published/).waitFor()
  report.steps.push('browser_version_origin_and_review_history')
  await page.setViewportSize({width:390,height:844})
  await page.waitForTimeout(400)
  if(await page.locator('.app-sidebar.mobile-open').count()) await page.locator('.mobile-close').click()
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.waitForTimeout(400)
  await shot('document-mobile')
  const overflow = await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth+2)
  assert.equal(overflow,false,'mobile horizontal overflow')
  await page.setViewportSize({width:1440,height:1000})
  await page.waitForTimeout(400)
  const archiveUpload = page.waitForResponse(r=>r.url().endsWith('/documents/upload') && r.request().method()==='POST')
  await page.locator('input[type=file]').setInputFiles({name:'archive-fixture.md',mimeType:'text/markdown',buffer:Buffer.from('# Archive fixture\n\nThis local document is archived before review and must remain private.')})
  const archived = await (await archiveUpload).json()
  await page.getByRole('button',{name:'归档上传资料',exact:true}).click()
  const [archiveResponse] = await Promise.all([
    page.waitForResponse(r=>r.url().endsWith(`/documents/${archived.id}/archive`)),
    page.locator('.el-message-box__btns .el-button--primary').click(),
  ])
  assert.equal(archiveResponse.status(),200)
  const archivedDetail = await (await context.request.get(`${api}/agent/knowledge-base/admin/documents/${archived.id}`,{headers})).json()
  assert.equal(archivedDetail.status,'ARCHIVED')
  report.steps.push('browser_archives_unreviewed_upload_preserving_original')
  assert.deepEqual(report.pageErrors,[])
  assert.deepEqual(report.apiErrors,[])
  report.passed=true
} catch(e) {
  report.error=String(e); await shot('failure'); throw e
} finally {
  fs.writeFileSync(path.join(root,'browser-result.json'),JSON.stringify(report,null,2))
  await browser.close()
}
